#!/usr/bin/env python3
"""
Generate the results documentation FROM THE ARTIFACTS (no hand-typed numbers).

    .venv/bin/python scripts/docs/generate_results_doc.py           # write docs/results.md + README block
    .venv/bin/python scripts/docs/generate_results_doc.py --check   # exit 1 if docs are out of date

Source: results-public/<run>/ (sanitized copy; metrics identical to the private originals) and
data/evaluation/ground_truth.json. The README block sits between <!-- RESULTS:START --> and <!-- RESULTS:END -->.
"""
from __future__ import annotations

import argparse
import collections
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RUN = "20261121T231031Z"
RUN_DIR = ROOT / "results-public" / RUN
ARMS = {"baseline-fixed100": "Fixed-size (100 tokens)", "improved-hierarchical": "Hierarchical (1500/300 tokens)"}
B, H = "baseline-fixed100", "improved-hierarchical"


def pct(x, digits=1):
    return "N/A" if x is None else f"{x * 100:.{digits}f}%"


def load():
    meta = json.loads((RUN_DIR / "run_metadata.json").read_text())
    s1 = json.loads((RUN_DIR / "summary.json").read_text())
    s2 = json.loads((RUN_DIR / "rescored_v2_summary.json").read_text())
    recs = [json.loads(l) for l in (RUN_DIR / "results.jsonl").read_text().splitlines() if l.strip()]
    v2 = {(r["id"], r["arm"]): r for r in map(json.loads, (RUN_DIR / "rescored_v2.jsonl").read_text().splitlines())}
    gt = json.loads((ROOT / "data/evaluation/ground_truth.json").read_text())["questions"]
    return meta, s1, s2, recs, v2, gt


def readme_block(meta, s1, s2) -> str:
    rows = [
        ("Answer: all expected facts matched - original v1 [string match]", pct(s1[B]["fully_correct_rate"]), pct(s1[H]["fully_correct_rate"])),
        ("Answer: all required facts matched - revised v2 [token match]", pct(s2[B]["v2_all_required_facts_matched"]), pct(s2[H]["v2_all_required_facts_matched"])),
        ("Retrieval: passage-evidence coverage@5 [token match]", pct(s1[B]["passage_evidence_coverage@k"]), pct(s1[H]["passage_evidence_coverage@k"])),
        ("Retrieval: all expected passages present@5", pct(s1[B]["all_passages_present@k"]), pct(s1[H]["all_passages_present@k"])),
        ("Unanswerable question (Q35) handled correctly", str(s1[B]["abstention_correct"][0]), str(s1[H]["abstention_correct"][0])),
        ("Input tokens (35 questions)", f"{s1[B]['input_tokens']:,}", f"{s1[H]['input_tokens']:,}"),
        ("Mean generation latency (service)", f"{s1[B]['avg_generate_ms']:.0f} ms", f"{s1[H]['avg_generate_ms']:.0f} ms"),
        ("Estimated generation cost", f"${s1[B]['cost_usd']:.6f}", f"${s1[H]['cost_usd']:.6f}"),
    ]
    out = ["<!-- RESULTS:START (generated by scripts/docs/generate_results_doc.py - do not edit by hand) -->",
           f"Run `{RUN}` · {meta['completed_items']}/{meta['planned_items']} items · model `{meta['model']}` · "
           f"temperature {meta['inference_config']['temperature']}, maxTokens {meta['inference_config']['maxTokens']} · "
           f"top-{meta['top_k']} · config fingerprint `{meta['config_fingerprint']}` · "
           f"total tracked cost ${meta['tracked_cost_usd']:.5f} · errors: {s1[B]['errors'] + s1[H]['errors']}", "",
           f"| Metric (lexical - not semantically verified) | {ARMS[B]} | {ARMS[H]} |", "|---|---|---|"]
    out += [f"| {a} | {b} | {c} |" for a, b, c in rows]
    out += ["<!-- RESULTS:END -->"]
    return "\n".join(out)


def results_md(meta, s1, s2, recs, v2, gt) -> str:
    by = {(r["id"], r["arm"]): r for r in recs}
    types = collections.Counter(q["question_type"] for q in gt)
    md = ["# Evaluation results", "",
          "> Generated by `scripts/docs/generate_results_doc.py` from `results-public/` (sanitized copy; every metric is",
          "> identical to the private original - see `tests/test_public_results.py`). **All scores are lexical** (string or",
          "> token matching) and are **not** semantic verification. Single run; no statistical significance is claimed.", "",
          "## Run", "", f"| | |", "|---|---|",
          f"| Run ID | `{RUN}` |", f"| Items | {meta['completed_items']} of {meta['planned_items']} (35 questions x 2 Knowledge Bases), stopped early: {meta['stopped_early']} |",
          f"| Generation model | `{meta['model']}` (Amazon Bedrock Converse) |",
          f"| Inference config | temperature {meta['inference_config']['temperature']}, maxTokens {meta['inference_config']['maxTokens']} |",
          f"| Retrieval | Bedrock Knowledge Bases `Retrieve`, top-{meta['top_k']}, semantic |",
          f"| Prompt version / config fingerprint | `{meta['prompt_template_version']}` / `{meta['config_fingerprint']}` (identical for both arms) |",
          f"| Total tracked generation cost | ${meta['tracked_cost_usd']:.6f} |", "",
          "## Dataset", "", "| Question type | Count |", "|---|---|"]
    md += [f"| {t} | {n} |" for t, n in sorted(types.items())] + [f"| **total** | **{len(gt)}** |", ""]
    md += ["## Headline comparison", "", readme_block(meta, s1, s2).split("\n", 1)[1].rsplit("\n", 1)[0], ""]
    md += ["## Full metric table (original v1 scoring)", "", f"| Metric | {ARMS[B]} | {ARMS[H]} |", "|---|---|---|"]
    for key, label, kind in [("keyword_recall@k", "Retrieval: expected-fact recall@5 [string]", "pct"),
                             ("passage_evidence_coverage@k", "Retrieval: passage-evidence coverage@5 [token]", "pct"),
                             ("all_passages_present@k", "Retrieval: all expected passages present@5", "pct"),
                             ("source_doc_hit@k", "Retrieval: expected documents retrieved@5", "pct"),
                             ("source_page_label_hit@k (informational)", "Retrieval: page-label hit (informational)", "pct"),
                             ("answer_keyword_coverage", "Answer: expected-fact coverage [string]", "pct"),
                             ("fully_correct_rate", "Answer: all expected facts matched [string]", "pct"),
                             ("false_abstentions", "False abstentions", "int"),
                             ("answers_with_citations", "Answers with a citation (v1 parser)", "pct"),
                             ("invalid_citation_ids", "Invalid citation IDs", "int"),
                             ("cited_chunk_keyword_support", "Cited-chunk keyword support [lexical]", "pct"),
                             ("truncated", "Truncated answers", "int"),
                             ("avg_context_chars", "Mean retrieved context (characters)", "num"),
                             ("input_tokens", "Input tokens", "num"), ("output_tokens", "Output tokens", "num"),
                             ("avg_retrieve_ms", "Mean Retrieve latency (ms)", "num"),
                             ("avg_generate_ms", "Mean generation latency, service (ms)", "num"),
                             ("cost_usd", "Estimated generation cost (USD)", "usd")]:
        f = {"pct": pct, "int": str, "num": lambda v: f"{v:,.0f}", "usd": lambda v: f"${v:.6f}"}[kind]
        md.append(f"| {label} | {f(s1[B][key])} | {f(s1[H][key])} |")
    md += ["", "## Original (v1) vs revised (v2) answer scoring", "",
           "v2 tolerates formatting differences (hyphens, spacing, thousands separators, unit plurals), rejects different",
           "numbers/identifiers, parses citations such as `[S1, Section 9]`, and scores Q30/Q31 on the facts the question asks",
           "for (`data/evaluation/scoring_revisions.json`). Original results are unchanged.", "",
           f"| | {ARMS[B]} | {ARMS[H]} |", "|---|---|---|",
           f"| All facts matched v1 -> v2 | {pct(s2[B]['v1_fully_correct'])} -> {pct(s2[B]['v2_all_required_facts_matched'])} | {pct(s2[H]['v1_fully_correct'])} -> {pct(s2[H]['v2_all_required_facts_matched'])} |",
           f"| Answer fact coverage v1 -> v2 | {pct(s2[B]['v1_answer_keyword_coverage'])} -> {pct(s2[B]['v2_answer_fact_coverage'])} | {pct(s2[H]['v1_answer_keyword_coverage'])} -> {pct(s2[H]['v2_answer_fact_coverage'])} |",
           f"| Answers with a parsed citation v1 -> v2 | {pct(s2[B]['v1_answers_with_citation'])} -> {pct(s2[B]['v2_answers_with_citation'])} | {pct(s2[H]['v1_answers_with_citation'])} -> {pct(s2[H]['v2_answers_with_citation'])} |",
           f"| Questions whose correctness changed | {', '.join(s2[B]['changed_vs_v1']) or 'none'} | {', '.join(s2[H]['changed_vs_v1']) or 'none'} |",
           f"| Automated triage: none / retrieval / generation | {' / '.join(str(s2[B]['failure_types'][k]) for k in ('none','retrieval','generation'))} | {' / '.join(str(s2[H]['failure_types'][k]) for k in ('none','retrieval','generation'))} |",
           "", "## By question type (original v1, all expected facts matched)", "",
           f"| Question type | n | {ARMS[B]} | {ARMS[H]} |", "|---|---|---|---|"]
    for t in sorted(types):
        bt, ht = s1[B]["by_question_type"][t], s1[H]["by_question_type"][t]
        md.append(f"| {t} | {bt['n']} | {pct(bt['fully_correct'])} | {pct(ht['fully_correct'])} |")
    md += ["", "## Questions where the two strategies differ (revised v2 scoring)", "",
           "| Q | Type | Fixed-size: matched / missing | Hierarchical: matched / missing |", "|---|---|---|---|"]
    for q in gt:
        a, b = v2.get((q["id"], B)), v2.get((q["id"], H))
        if not a or not b or a["v2"] is None or b["v2"] is None:
            continue
        ka = (a["v2"]["all_required_facts_matched"], a["v2"]["abstained"])
        kb = (b["v2"]["all_required_facts_matched"], b["v2"]["abstained"])
        if ka != kb:
            fmt = lambda v: ("abstained" if v["abstained"] else
                             f"{len(v['matched_facts'])}/{len(v['required_facts'])}" + (f" (missing: {', '.join(v['missing_facts'])})" if v["missing_facts"] else ""))
            md.append(f"| {q['id']} | {q['question_type']} | {fmt(a['v2'])} | {fmt(b['v2'])} |")
    md += ["", "Reviewer notes on retrieval vs generation failures (Q03, Q15, Q22, Q30, Q31, Q34) are in",
           "`data/evaluation/failure_analysis_20261121T231031Z.json` - an AI assistant's reading, not SME-verified.", "",
           "## Limitations", "",
           "- Single run per strategy; LLM output varied between runs at temperature 0 (Q18 wording changed between the",
           "  Q18-only test run and the full run). No confidence intervals or significance tests.",
           "- Lexical scoring only: it can miss correct paraphrases and cannot detect invented claims that avoid the",
           "  expected keywords (see Q34 fixed-size in the failure analysis).",
           "- 35 questions over 5 synthetic documents (~6K words); results may not transfer to larger or real corpora.",
           "- One small generation model (Amazon Nova Micro); long-context errors may differ with larger models.",
           "- Cited-chunk fact support (v2) is N/A for this run because only 160-character previews were stored.", ""]
    return "\n".join(md)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    meta, s1, s2, recs, v2, gt = load()
    new_results = results_md(meta, s1, s2, recs, v2, gt)
    readme_path, results_path = ROOT / "README.md", ROOT / "docs" / "results.md"
    readme = readme_path.read_text()
    start, end = readme.find("<!-- RESULTS:START"), readme.find("<!-- RESULTS:END -->")
    if start == -1 or end == -1:
        print("README.md has no RESULTS markers"); return 1
    new_readme = readme[:start] + readme_block(meta, s1, s2) + readme[end + len("<!-- RESULTS:END -->"):]
    if args.check:
        stale = [p.name for p, new in ((results_path, new_results), (readme_path, new_readme))
                 if not p.exists() or p.read_text() != new]
        print("results docs up to date" if not stale else f"OUT OF DATE: {stale}")
        return 1 if stale else 0
    results_path.write_text(new_results); readme_path.write_text(new_readme)
    print(f"wrote {results_path.relative_to(ROOT)} and README results block")
    return 0


if __name__ == "__main__":
    sys.exit(main())
